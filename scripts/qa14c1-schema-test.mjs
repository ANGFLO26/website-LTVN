import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const schemaPath = path.join(rootDir, 'api', 'src', 'database', 'schema.ts');
const migrationPath = path.join(rootDir, 'api', 'drizzle', '0001_add_news_event_translations.sql');

const schemaContent = fs.readFileSync(schemaPath, 'utf8');
const migrationContent = fs.readFileSync(migrationPath, 'utf8');

const tests = [];

function test(name, fn) {
  try {
    fn();
    tests.push({ name, pass: true });
    console.log(`[PASS] ${name}`);
  } catch (err) {
    tests.push({ name, pass: false, error: err.message });
    console.error(`[FAIL] ${name}: ${err.message}`);
  }
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

console.log('--- QA-14C1 STATIC SCHEMA & MIGRATION TEST ---');

// 1. Có news_event_translations table
test('1. news_event_translations table definition exists in schema and migration', () => {
  assert(/export const newsEventTranslations\s*=\s*pgTable\(\s*['"]news_event_translations['"]/.test(schemaContent), 'schema.ts missing newsEventTranslations export');
  assert(migrationContent.includes('CREATE TABLE "news_event_translations"'), 'migration SQL missing CREATE TABLE news_event_translations');
});

// 2. Có FK tới news_events (ON DELETE CASCADE)
test('2. Foreign Key references news_events(id) ON DELETE CASCADE', () => {
  assert(schemaContent.includes(".references(() => newsEvents.id, { onDelete: 'cascade' })"), 'schema.ts FK missing onDelete cascade');
  assert(migrationContent.includes('REFERENCES "public"."news_events"("id") ON DELETE cascade'), 'migration SQL missing FK to news_events with ON DELETE cascade');
});

// 3. Có locale check 'vi' / 'en'
test('3. Locale CHECK constraint restricts to vi and en', () => {
  assert(schemaContent.includes("check('news_event_translations_locale_check', sql`${table.locale} in ('vi', 'en')`)"), 'schema.ts missing locale check constraint');
  assert(migrationContent.includes('CHECK ("news_event_translations"."locale" in (\'vi\', \'en\'))'), 'migration SQL missing locale check constraint');
});

// 4. Có unique (news_event_id, locale)
test('4. Unique constraint on (news_event_id, locale)', () => {
  assert(schemaContent.includes("unique('news_event_translations_event_locale_unique').on(table.newsEventId, table.locale)"), 'schema.ts missing unique(newsEventId, locale)');
  assert(migrationContent.includes('UNIQUE("news_event_id","locale")'), 'migration SQL missing UNIQUE(news_event_id, locale)');
});

// 5. Có slug uniqueness strategy đã chọn (Global unique)
test('5. Slug uniqueness constraint matches selected v1 strategy (global unique)', () => {
  assert(schemaContent.includes("slug: varchar('slug', { length: 255 }).notNull().unique()"), 'schema.ts slug must be unique');
  assert(migrationContent.includes('UNIQUE("slug")'), 'migration SQL missing UNIQUE(slug)');
});

// 6. Có backfill locale = 'vi'
test('6. Backfill statement exists and sets locale to vi', () => {
  assert(migrationContent.includes("INSERT INTO \"news_event_translations\""), 'migration SQL missing INSERT statement');
  assert(migrationContent.includes("'vi'"), "migration SQL backfill missing 'vi' literal");
});

// 7. Copy title, slug, short_description, content, location từ legacy row
test('7. Backfill copies title, slug, short_description, content, location from legacy news_events', () => {
  const insertFields = [
    '"news_event_id"',
    '"locale"',
    '"title"',
    '"slug"',
    '"short_description"',
    '"content"',
    '"location"',
    '"created_at"',
    '"updated_at"'
  ];
  for (const field of insertFields) {
    assert(migrationContent.includes(field), `migration SQL insert missing field ${field}`);
  }
  const selectFields = [
    '"id"',
    "'vi'",
    '"title"',
    '"slug"',
    '"short_description"',
    '"content"',
    '"location"',
    '"created_at"',
    '"updated_at"'
  ];
  for (const field of selectFields) {
    assert(migrationContent.includes(field), `migration SQL select missing field ${field}`);
  }
  assert(migrationContent.includes('FROM "news_events"'), 'migration SQL backfill must select FROM news_events');
});

// 8. Không insert locale = 'en'
test('8. Exactly 0 English records generated by migration backfill', () => {
  const insertIndex = migrationContent.indexOf('INSERT INTO "news_event_translations"');
  assert(insertIndex !== -1, 'Backfill insert not found');
  const backfillSql = migrationContent.slice(insertIndex);
  assert(!backfillSql.includes("'en'"), "migration SQL backfill must NOT insert 'en'");
  assert(backfillSql.includes("'vi'"), "migration SQL backfill must insert 'vi'");
});

// 9. Không DROP legacy columns
test('9. No DROP COLUMN statements present in migration (additive only)', () => {
  assert(!migrationContent.toLowerCase().includes('drop column'), 'migration SQL must NOT drop any column');
  assert(!migrationContent.toLowerCase().includes('drop table'), 'migration SQL must NOT drop any table');
});

// 10. Không ALTER semantics của current type/status
test('10. Current news_events type and status semantics are strictly preserved', () => {
  // Check schema news_events type check constraint
  assert(schemaContent.includes("check('news_events_type_check', sql`${table.type} in ('news', 'event')`)"), 'news_events type check altered!');
  assert(schemaContent.includes("check('news_events_status_check', sql`${table.status} in ('draft', 'published', 'archived')`)"), 'news_events status check altered!');
  assert(!migrationContent.toLowerCase().includes('alter table "news_events"'), 'migration SQL must not alter news_events table');
});

const failedCount = tests.filter((t) => !t.pass).length;
console.log(`\nResult: ${tests.length - failedCount}/${tests.length} tests passed.`);

if (failedCount > 0) {
  process.exit(1);
} else {
  console.log('ALL 10 MIGRATION RULES VERIFIED SUCCESSFULLY.');
  process.exit(0);
}
